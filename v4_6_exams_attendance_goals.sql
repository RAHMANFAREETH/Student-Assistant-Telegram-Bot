-- =========================================================
-- EXAMS
-- =========================================================

create table if not exists public.exams (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    chat_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    title text not null,
    exam_at timestamptz not null,
    location text,
    notes text,

    alert_7d_sent boolean not null default false,
    alert_1d_sent boolean not null default false,
    alert_1h_sent boolean not null default false,

    created_at timestamptz not null default now()
);

create index if not exists exams_user_idx
on public.exams(user_id, exam_at);

create index if not exists exams_alert_idx
on public.exams(
    exam_at,
    alert_7d_sent,
    alert_1d_sent,
    alert_1h_sent
);

alter table public.exams enable row level security;

grant select, insert, update, delete
on public.exams
to service_role;


-- =========================================================
-- ATTENDANCE
-- =========================================================

create table if not exists public.attendance_records (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete cascade,

    class_date date not null,
    status text not null
        check (status in ('present', 'absent', 'late', 'excused')),

    note text,
    created_at timestamptz not null default now(),

    unique(user_id, subject_id, class_date)
);

create index if not exists attendance_user_subject_idx
on public.attendance_records(user_id, subject_id, class_date desc);

alter table public.attendance_records enable row level security;

grant select, insert, update, delete
on public.attendance_records
to service_role;


-- =========================================================
-- STUDY GOALS
-- =========================================================

create table if not exists public.study_goals (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    title text not null,
    description text,
    target_date date,
    status text not null default 'pending'
        check (status in ('pending', 'completed')),

    created_at timestamptz not null default now(),
    completed_at timestamptz
);

create index if not exists study_goals_user_idx
on public.study_goals(user_id, status, target_date);

alter table public.study_goals enable row level security;

grant select, insert, update, delete
on public.study_goals
to service_role;


-- =========================================================
-- TELEGRAM QUEUE HELPER
-- Safe to replace if already created by earlier versions.
-- =========================================================

create extension if not exists pg_net;

create or replace function public.queue_telegram_message(
    p_chat_id bigint,
    p_text text
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
    token text;
    request_id bigint;
begin

    select decrypted_secret
    into token
    from vault.decrypted_secrets
    where name = 'telegram_bot_token'
    limit 1;

    if token is null or token = '' then
        raise exception 'telegram_bot_token was not found in Vault';
    end if;

    select net.http_post(
        url := 'https://api.telegram.org/bot'
               || token
               || '/sendMessage',

        headers := jsonb_build_object(
            'Content-Type',
            'application/json'
        ),

        body := jsonb_build_object(
            'chat_id',
            p_chat_id,
            'text',
            p_text
        ),

        timeout_milliseconds := 5000
    )
    into request_id;

    return request_id;
end;
$$;


-- =========================================================
-- EXAM ALERT FUNCTION
-- =========================================================

create or replace function public.send_exam_alerts()
returns void
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
    r record;
    subject_name text;
    local_exam text;
begin

    -- 7 DAY ALERT
    for r in
        select *
        from public.exams e
        where e.alert_7d_sent = false
          and e.exam_at > now() + interval '1 day'
          and e.exam_at <= now() + interval '7 days'
        order by e.exam_at
        for update skip locked
    loop

        select s.name
        into subject_name
        from public.subjects s
        where s.id = r.subject_id
        limit 1;

        local_exam := to_char(
            r.exam_at at time zone 'Asia/Colombo',
            'DD-MM-YYYY HH12:MI AM'
        );

        perform public.queue_telegram_message(
            r.chat_id,
            '📝 Exam Reminder'
            || E'\n\n📅 Exam within 7 days'
            || E'\n📌 ' || r.title
            || case
                when subject_name is not null
                then E'\n📚 ' || subject_name
                else ''
               end
            || E'\n🕒 ' || local_exam
            || case
                when r.location is not null and r.location <> ''
                then E'\n📍 ' || r.location
                else ''
               end
            || E'\n\nStart revising early and avoid last-minute pressure.'
        );

        update public.exams
        set alert_7d_sent = true
        where id = r.id;

    end loop;


    -- 1 DAY ALERT
    for r in
        select *
        from public.exams e
        where e.alert_1d_sent = false
          and e.exam_at > now() + interval '1 hour'
          and e.exam_at <= now() + interval '1 day'
        order by e.exam_at
        for update skip locked
    loop

        select s.name
        into subject_name
        from public.subjects s
        where s.id = r.subject_id
        limit 1;

        local_exam := to_char(
            r.exam_at at time zone 'Asia/Colombo',
            'DD-MM-YYYY HH12:MI AM'
        );

        perform public.queue_telegram_message(
            r.chat_id,
            '🚨 Exam Tomorrow / Within 24 Hours'
            || E'\n\n📌 ' || r.title
            || case
                when subject_name is not null
                then E'\n📚 ' || subject_name
                else ''
               end
            || E'\n🕒 ' || local_exam
            || case
                when r.location is not null and r.location <> ''
                then E'\n📍 ' || r.location
                else ''
               end
            || E'\n\nReview key points and prepare what you need.'
        );

        update public.exams
        set
            alert_7d_sent = true,
            alert_1d_sent = true
        where id = r.id;

    end loop;


    -- 1 HOUR ALERT
    for r in
        select *
        from public.exams e
        where e.alert_1h_sent = false
          and e.exam_at > now()
          and e.exam_at <= now() + interval '1 hour'
        order by e.exam_at
        for update skip locked
    loop

        select s.name
        into subject_name
        from public.subjects s
        where s.id = r.subject_id
        limit 1;

        local_exam := to_char(
            r.exam_at at time zone 'Asia/Colombo',
            'DD-MM-YYYY HH12:MI AM'
        );

        perform public.queue_telegram_message(
            r.chat_id,
            '⏰ Exam Starts Soon'
            || E'\n\n📌 ' || r.title
            || case
                when subject_name is not null
                then E'\n📚 ' || subject_name
                else ''
               end
            || E'\n🕒 ' || local_exam
            || case
                when r.location is not null and r.location <> ''
                then E'\n📍 ' || r.location
                else ''
               end
            || E'\n\nBe ready and arrive on time.'
        );

        update public.exams
        set
            alert_7d_sent = true,
            alert_1d_sent = true,
            alert_1h_sent = true
        where id = r.id;

    end loop;

end;
$$;


