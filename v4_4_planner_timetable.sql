-- -----------------------------
-- WEEKLY TIMETABLE
-- day_of_week: Monday=0 ... Sunday=6
-- -----------------------------

create table if not exists public.timetable_entries (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,
    title text not null,
    day_of_week integer not null
        check (day_of_week between 0 and 6),
    start_time time not null,
    end_time time not null,
    location text,
    created_at timestamptz not null default now(),

    check (end_time > start_time)
);

create index if not exists timetable_user_day_idx
on public.timetable_entries(user_id, day_of_week, start_time);

alter table public.timetable_entries enable row level security;

grant select, insert, update, delete
on public.timetable_entries
to service_role;


-- -----------------------------
-- STUDY SESSIONS
-- -----------------------------

create table if not exists public.study_sessions (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    chat_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    planned_minutes integer not null
        check (planned_minutes between 1 and 360),

    started_at timestamptz not null default now(),
    planned_end_at timestamptz not null,

    ended_at timestamptz,
    actual_minutes integer,

    status text not null default 'active'
        check (status in ('active', 'completed', 'cancelled')),

    alert_sent boolean not null default false,
    created_at timestamptz not null default now()
);

create index if not exists study_sessions_user_idx
on public.study_sessions(user_id, started_at desc);

create index if not exists study_sessions_active_idx
on public.study_sessions(status, planned_end_at, alert_sent);

alter table public.study_sessions enable row level security;

grant select, insert, update, delete
on public.study_sessions
to service_role;


-- -----------------------------
-- TELEGRAM QUEUE HELPER
-- Re-created safely so V4.4 also works even if V4.1
-- was not installed earlier.
-- -----------------------------

create extension if not exists pg_net;

create or replace function public.queue_telegram_message(
    p_chat_id bigint,
    p_text text
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
    token text;
    request_id bigint;
begin

    select decrypted_secret
    into token
    from vault.decrypted_secrets
    where name = 'telegram_bot_token'
    limit 1;

    if token is null or token = '' then
        raise exception 'telegram_bot_token was not found in Vault';
    end if;

    select net.http_post(
        url := 'https://api.telegram.org/bot'
               || token
               || '/sendMessage',

        headers := jsonb_build_object(
            'Content-Type',
            'application/json'
        ),

        body := jsonb_build_object(
            'chat_id',
            p_chat_id,
            'text',
            p_text
        ),

        timeout_milliseconds := 5000
    )
    into request_id;

    return request_id;
end;
$$;


-- -----------------------------
-- FINISH DUE STUDY SESSIONS
-- -----------------------------

create or replace function public.finish_due_study_sessions()
returns void
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
    r record;
    subject_name text;
begin

    for r in
        select
            s.id,
            s.chat_id,
            s.subject_id,
            s.planned_minutes,
            s.started_at,
            s.planned_end_at
        from public.study_sessions s
        where s.status = 'active'
          and s.alert_sent = false
          and s.planned_end_at <= now()
        order by s.planned_end_at
        for update skip locked
    loop

        select sub.name
        into subject_name
        from public.subjects sub
        where sub.id = r.subject_id
        limit 1;

        perform public.queue_telegram_message(
            r.chat_id,
            '⏱ Study Session Complete!'
            || E'\n\n✅ Focus time: '
            || r.planned_minutes::text
            || ' minutes'
            || case
                when subject_name is not null
                then E'\n📚 ' || subject_name
                else ''
               end
            || E'\n\nTake a short break, drink some water, '
            || 'then continue when you are ready. 🌿'
        );

        update public.study_sessions
        set
            status = 'completed',
            ended_at = r.planned_end_at,
            actual_minutes = r.planned_minutes,
            alert_sent = true
        where id = r.id;

    end loop;
end;
$$;


-- -----------------------------
-- CRON: check every minute
-- -----------------------------

create extension if not exists pg_cron;

select cron.schedule(
    'student-study-session-check',
    '* * * * *',
    $$select public.finish_due_study_sessions();$$
);


