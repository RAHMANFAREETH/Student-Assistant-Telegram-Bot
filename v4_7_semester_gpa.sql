-- -----------------------------
-- SEMESTERS
-- -----------------------------

create table if not exists public.semesters (
    id bigint generated by default as identity primary key,
    user_id bigint not null,

    name text not null,
    start_date date,
    end_date date,

    gpa_scale numeric(6,2) not null default 4.00
        check (gpa_scale > 0),

    status text not null default 'active'
        check (status in ('active', 'completed')),

    created_at timestamptz not null default now()
);

create index if not exists semesters_user_idx
on public.semesters(user_id, created_at desc);

create unique index if not exists semesters_one_active_per_user_idx
on public.semesters(user_id)
where status = 'active';

alter table public.semesters enable row level security;

grant select, insert, update, delete
on public.semesters
to service_role;


-- -----------------------------
-- COURSE RESULTS
-- -----------------------------

create table if not exists public.course_results (
    id bigint generated by default as identity primary key,
    user_id bigint not null,

    semester_id bigint not null
        references public.semesters(id)
        on delete cascade,

    subject_id bigint
        references public.subjects(id)
        on delete set null,

    subject_name text not null,

    credits numeric(6,2) not null
        check (credits > 0),

    grade_label text,

    grade_points numeric(7,3) not null
        check (grade_points >= 0),

    score_percent numeric(6,2)
        check (
            score_percent is null
            or (
                score_percent >= 0
                and score_percent <= 100
            )
        ),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    unique(user_id, semester_id, subject_id)
);

create index if not exists course_results_user_idx
on public.course_results(user_id, semester_id);

create index if not exists course_results_subject_idx
on public.course_results(user_id, subject_id);

alter table public.course_results enable row level security;

grant select, insert, update, delete
on public.course_results
to service_role;
