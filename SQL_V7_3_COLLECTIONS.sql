-- V7.3 — Save custom private AI Study note collections.
-- Run in your EXISTING Supabase project, after SQL_V7_2_NOTE_ORGANIZER.sql.
-- Server uses SUPABASE_SECRET_KEY/service-role key. No direct client access.
-- Never modifies existing notes, AI settings, or earlier tables.
CREATE TABLE IF NOT EXISTS public.ai_study_collections_v73 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 60),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id, user_id)
);
-- Case-insensitive duplicate names rejected per student; exact text preserved.
CREATE UNIQUE INDEX IF NOT EXISTS ai_study_collections_v73_unique_name
    ON public.ai_study_collections_v73 (user_id, lower(name));
CREATE INDEX IF NOT EXISTS ai_study_collections_v73_owner_idx
    ON public.ai_study_collections_v73 (user_id, id DESC);
CREATE TABLE IF NOT EXISTS public.ai_study_collection_notes_v73 (
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    collection_id BIGINT NOT NULL,
    note_id BIGINT NOT NULL CHECK (note_id > 0),
    added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, collection_id, note_id),
    CONSTRAINT ai_study_collection_notes_owner_fk
       FOREIGN KEY (collection_id, user_id)
       REFERENCES public.ai_study_collections_v73 (id, user_id)
       ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ai_study_collection_notes_v73_recent_idx
    ON public.ai_study_collection_notes_v73 (user_id, collection_id, note_id DESC);
ALTER TABLE public.ai_study_collections_v73 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_study_collection_notes_v73 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ai_study_collections_v73 FROM anon, authenticated;
REVOKE ALL ON public.ai_study_collection_notes_v73 FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.ai_study_collections_v73_id_seq FROM anon, authenticated;
-- No user-facing RLS policy; service-role/backend only.
-- Membership note ownership is checked by the Telegram backend on add and read.
