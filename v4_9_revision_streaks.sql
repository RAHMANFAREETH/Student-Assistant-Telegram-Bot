-- -----------------------------
-- STUDY PREFERENCES
-- -----------------------------

create table if not exists public.study_preferences (
    user_id bigint primary key,

    daily_target_minutes integer not null default 60
        check (daily_target_minutes between 1 and 1440),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.study_preferences enable row level security;

grant select, insert, update, delete
on public.study_preferences
to service_role;


-- -----------------------------
-- REVISION PLANS
-- -----------------------------

create table if not exists public.revision_plans (
    id bigint generated by default as identity primary key,
    user_id bigint not null,

    exam_id bigint
        references public.exams(id)
        on delete cascade,

    subject_id bigint
        references public.subjects(id)
        on delete set null,

    title text not null,

    start_date date not null,
    end_date date not null,

    status text not null default 'active'
        check (status in ('active', 'completed')),

    created_at timestamptz not null default now(),

    check (end_date >= start_date)
);

create index if not exists revision_plans_user_idx
on public.revision_plans(user_id, status, end_date);

alter table public.revision_plans enable row level security;

grant select, insert, update, delete
on public.revision_plans
to service_role;


-- -----------------------------
-- REVISION TASKS
-- -----------------------------

create table if not exists public.revision_tasks (
    id bigint generated by default as identity primary key,
    user_id bigint not null,

    plan_id bigint not null
        references public.revision_plans(id)
        on delete cascade,

    task_date date not null,

    topic text not null,

    status text not null default 'pending'
        check (status in ('pending', 'completed')),

    completed_at timestamptz,

    created_at timestamptz not null default now()
);

create index if not exists revision_tasks_user_date_idx
on public.revision_tasks(user_id, task_date, status);

create index if not exists revision_tasks_plan_idx
on public.revision_tasks(plan_id, task_date);

alter table public.revision_tasks enable row level security;

grant select, insert, update, delete
on public.revision_tasks
to service_role;
