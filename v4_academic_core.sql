-- =========================================================
-- STUDENT ASSISTANT BOT V4 - ACADEMIC CORE
-- Subjects + Assignments
-- =========================================================

create table if not exists public.subjects (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    name text not null,
    code text,
    created_at timestamptz not null default now()
);

create unique index if not exists subjects_user_name_unique_idx
on public.subjects (user_id, lower(name));

create index if not exists subjects_user_id_idx
on public.subjects (user_id);


create table if not exists public.assignments (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,
    title text not null,
    description text,
    due_at timestamptz not null,
    priority text not null default 'medium'
        check (priority in ('low', 'medium', 'high')),
    status text not null default 'pending'
        check (status in ('pending', 'completed')),
    created_at timestamptz not null default now(),
    completed_at timestamptz
);

create index if not exists assignments_user_id_idx
on public.assignments (user_id);

create index if not exists assignments_subject_id_idx
on public.assignments (subject_id);

create index if not exists assignments_due_idx
on public.assignments (user_id, status, due_at);


alter table public.subjects enable row level security;
alter table public.assignments enable row level security;


grant select, insert, update, delete
on public.subjects
to service_role;

grant select, insert, update, delete
on public.assignments
to service_role;
