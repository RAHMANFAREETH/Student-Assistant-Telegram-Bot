-- STUDENT ASSISTANT BOT V4.2
-- Flashcards + Quiz + Study Progress
-- =========================================================

create table if not exists public.flashcards (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,
    question text not null,
    answer text not null,

    times_seen integer not null default 0,
    correct_count integer not null default 0,
    wrong_count integer not null default 0,
    mastered boolean not null default false,

    created_at timestamptz not null default now()
);

create index if not exists flashcards_user_idx
on public.flashcards(user_id);

create index if not exists flashcards_subject_idx
on public.flashcards(user_id, subject_id);

create index if not exists flashcards_mastered_idx
on public.flashcards(user_id, mastered);


create table if not exists public.quiz_attempts (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    total_questions integer not null,
    correct_answers integer not null,
    wrong_answers integer not null,
    score_percent numeric(5,2) not null,

    created_at timestamptz not null default now()
);

create index if not exists quiz_attempts_user_idx
on public.quiz_attempts(user_id, created_at desc);

create index if not exists quiz_attempts_subject_idx
on public.quiz_attempts(user_id, subject_id, created_at desc);


alter table public.flashcards enable row level security;
alter table public.quiz_attempts enable row level security;


grant select, insert, update, delete
on public.flashcards
to service_role;

grant select, insert, update, delete
on public.quiz_attempts
to service_role;
