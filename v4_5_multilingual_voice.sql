-- -----------------------------
-- VOICE NOTES
-- -----------------------------

create table if not exists public.voice_notes (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    title text not null,

    telegram_file_id text not null,
    telegram_file_unique_id text,
    duration_seconds integer,

    transcript text,
    transcript_language text,

    created_at timestamptz not null default now()
);

create index if not exists voice_notes_user_idx
on public.voice_notes(user_id, created_at desc);

create index if not exists voice_notes_subject_idx
on public.voice_notes(user_id, subject_id);

alter table public.voice_notes enable row level security;

grant select, insert, update, delete
on public.voice_notes
to service_role;


-- -----------------------------
-- MULTILINGUAL VOCABULARY
-- -----------------------------

create table if not exists public.language_vocabulary (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    subject_id bigint references public.subjects(id) on delete set null,

    language_code text not null,
    language_name text not null,

    term text not null,
    meaning text not null,
    example_text text,

    times_seen integer not null default 0,
    correct_count integer not null default 0,
    wrong_count integer not null default 0,
    mastered boolean not null default false,

    created_at timestamptz not null default now()
);

create index if not exists language_vocabulary_user_idx
on public.language_vocabulary(user_id, created_at desc);

create index if not exists language_vocabulary_language_idx
on public.language_vocabulary(user_id, language_code);

create index if not exists language_vocabulary_subject_idx
on public.language_vocabulary(user_id, subject_id);

create index if not exists language_vocabulary_mastered_idx
on public.language_vocabulary(user_id, mastered);

alter table public.language_vocabulary enable row level security;

grant select, insert, update, delete
on public.language_vocabulary
to service_role;
